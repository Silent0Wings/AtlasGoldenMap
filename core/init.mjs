/**
 * init.mjs — non-interactive setup: `node core/cli.mjs init --url <app> [--command ...]`.
 * Moves the demo config aside (or a real one, with --force), clears the demo's output and writes a
 * starter atlas.config.ts. renderConfig() is the template the interactive `config` uses too.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const DEFAULT_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DEMO = 'examples/demo-site';
const BOOL_FLAGS = new Set(['dark', 'mobile', 'crawl', 'force']);
const VALUE_FLAGS = new Set(['url', 'command', 'cwd', 'static-dir', 'title', 'path', 'theme-key']);
const CLEAR = ['goldens', 'review', 'shots', 'atlas.crawl.json'];

const bad = m => new Error(`init: ${m}`);

/** Accepts `--k v` and `--k=v`. Unknown flags and missing values throw. */
function parseArgs(argv) {
  const opts = {};
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (!a.startsWith('--')) throw bad(`unexpected argument "${a}". Flags start with --`);
    const eq = a.indexOf('=');
    const k = (eq < 0 ? a : a.slice(0, eq)).slice(2);
    if (!BOOL_FLAGS.has(k) && !VALUE_FLAGS.has(k)) throw bad(`unknown flag --${k}`);
    if (BOOL_FLAGS.has(k)) {
      if (eq >= 0) throw bad(`--${k} takes no value`);
      opts[k] = true;
      continue;
    }
    let v = eq < 0 ? argv[++i] : a.slice(eq + 1);
    if (v === undefined || v.startsWith('--') || !v.trim()) throw bad(`--${k} needs a value`);
    opts[k] = v;
  }
  return opts;
}

function validate(opts) {
  if (!opts.url) throw bad('--url is required, e.g. --url http://127.0.0.1:8766');
  let u;
  try { u = new URL(opts.url); } catch { throw bad(`--url "${opts.url}" is not a URL`); }
  if (u.protocol !== 'http:' && u.protocol !== 'https:') throw bad(`--url must start with http:// or https://`);
  if (opts.command && opts['static-dir']) throw bad('pass either --command or --static-dir, not both');
  if (opts.cwd && !opts.command) throw bad('--cwd only applies with --command');
  if (opts['static-dir'] && !u.port) throw bad('--static-dir needs a port in --url, e.g. http://127.0.0.1:8091');
  if (opts.path !== undefined && !opts.path.startsWith('/')) throw bad(`--path must start with /, got "${opts.path}"`);
}

/** The starter config. Same template as the interactive `config`; unset optional parts are left out. */
export function renderConfig({ title, baseURL, server, start, variants, crawl }) {
  return `/**
 * atlas.config.ts — the ONLY project-specific file for Golden Map Atlas (generated by \`init\` or \`config\`).
 * Add a node per page / modal / tab you want in the atlas. See README.md → "Config reference".
 */
import { defineAtlas, click, fill, seq, type UINode } from './core/atlas';

const nodes: UINode[] = [
  { id: 'home', label: 'Home', kind: 'page', url: ${JSON.stringify(start)}, ready: 'body',
    components: [
      // { name: 'header', label: 'Header', selector: 'header' },
    ] },
  // A state reached by interacting with its parent:
  // { id: 'home:menu', label: 'Menu open', kind: 'state', parent: 'home', steps: click('[data-testid=menu]'), ready: '[role=menu]' },
];

export default defineAtlas({
  title: ${JSON.stringify(title)},
  baseURL: ${JSON.stringify(baseURL)},
  ${server || '// server: { command: \'npm run dev\', cwd: \'..\' },   // app is expected to be running already'}

  variants: [
${variants.join('\n')}
  ],

  nodes,
  root: 'home',
  fixtures: {
    // 'signed-in': { localStorage: { token: 'test' } },   // nodes opt in with fixture: 'signed-in'
  },
  mask: [
    // '[data-testid=clock]',   // dynamic regions: clocks, avatars, counters
  ],
${crawl ? `  crawl: { start: [${JSON.stringify(start)}], maxPages: 100 },\n` : ''}});
`;
}

/**
 * Non-interactive init. Order matters: validate, refuse, move the config, write the new one, and only
 * then clear. Nothing is touched when validation or the refusal throws.
 * Returns { crawl } so the caller can run the crawler next.
 */
export async function runInit(argv, { root = DEFAULT_ROOT, log = console.log } = {}) {
  const opts = parseArgs(argv);
  validate(opts);

  const slash = s => s.replace(/\\/g, '/');
  const start = opts.path ?? '/';
  const themeKey = opts['theme-key'];
  const dark = !!opts.dark || themeKey !== undefined;
  const themeOf = v => (themeKey ? `, localStorage: { ${JSON.stringify(themeKey)}: '${v}' }` : '');

  let server = '';
  if (opts.command) server = `server: { command: ${JSON.stringify(opts.command)}${opts.cwd ? `, cwd: ${JSON.stringify(slash(opts.cwd))}` : ''} },`;
  else if (opts['static-dir']) server = `server: { staticDir: ${JSON.stringify(slash(opts['static-dir']))} },`;

  const variants = [`    { name: 'light', label: 'Light', colorScheme: 'light'${themeOf('light')} },`];
  if (dark) variants.push(`    { name: 'dark', label: 'Dark', colorScheme: 'dark'${themeOf('dark')} },`);
  if (opts.mobile) variants.push(`    { name: 'mobile', label: 'Mobile', colorScheme: 'light', viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true${themeOf('light')} },`);

  const src = renderConfig({
    title: opts.title ?? path.basename(path.resolve(root, '..')),
    baseURL: opts.url,
    server,
    start,
    variants,
    crawl: !!opts.crawl,
  });

  // refuse before anything moves: a real config is only replaced with --force
  const file = path.join(root, 'atlas.config.ts');
  const exists = fs.existsSync(file);
  const isDemo = exists && fs.readFileSync(file, 'utf8').includes(DEMO);
  if (exists && !isDemo && !opts.force) {
    throw bad('atlas.config.ts is not the demo config, so it would be replaced. Re-run with --force to back it up and replace it (goldens/, review/ and shots/ are then cleared).');
  }

  const stamp = new Date().toISOString().replace(/[:.]/g, '-');
  if (exists) {
    let dest = path.join(root, isDemo ? 'atlas.config.demo.ts' : `atlas.config.backup-${stamp}.ts`);
    if (isDemo && fs.existsSync(dest) && fs.readFileSync(dest, 'utf8') === fs.readFileSync(file, 'utf8')) {
      fs.rmSync(file);   // a plain copy of the shipped demo config needs no second backup
      log('Removed atlas.config.ts (a copy of atlas.config.demo.ts)');
    } else {
      if (isDemo && fs.existsSync(dest)) dest = path.join(root, `atlas.config.demo-${stamp}.ts`);
      fs.renameSync(file, dest);
      log(`Moved atlas.config.ts to ${path.basename(dest)}`);
    }
  }

  fs.writeFileSync(file, src);
  log('Wrote atlas.config.ts');

  for (const name of CLEAR) {
    const p = path.join(root, name);
    if (!fs.existsSync(p)) continue;
    fs.rmSync(p, { recursive: true, force: true });
    log(`Cleared ${name}${name === 'goldens' && opts.force && !isDemo ? ' (restore them from git if they were committed)' : ''}`);
  }

  return { crawl: !!opts.crawl };
}
